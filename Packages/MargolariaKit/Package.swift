// swift-tools-version: 6.1
//
// Package.swift: the manifest for MargolariaKit, all of Margolaria's code
// that talks to OpenUSD and MaterialX.
//
// SWIFT: A Swift package is described by Swift code, not by a data file. This
// file is compiled and run by SwiftPM (`swift build`, `swift test`, or Xcode)
// to find out what the package contains. The comment on the very first line
// is not decoration: it tells SwiftPM which manifest API version to use.
//
// The package has these "targets" (a target is roughly a library or a module),
// in two layers:
//
//   MXBridge        C++. The only code that includes MaterialX headers.
//   MXKit           Swift. The MaterialX API the app uses (documents, libraries).
//   ViewportBridge  Objective-C++. The only code that includes OpenUSD headers;
//                   runs Hydra Storm on Metal.
//   ViewportKit     Swift. The SwiftUI viewport, with OCIO's view transform.
//   PreviewKit      Swift + Metal. Draws MaterialX shaders (generated by MXKit)
//                   as swatches, with our own small renderer; and what the
//                   viewport shares with it (the studio light, DisplayPass).
//   GraphKit        Swift. The node graph canvas, and building it from MXKit's graphs.
//   ColorBridge     C++. The only code that includes OpenColorIO headers.
//   ColorKit        Swift. Colour management: OCIO configs and conversions.
//   PythonBridge    C++. The only code that talks to Python: embeds the
//                   interpreter and hands it documents (M6).
//   ScriptKit       Swift. Runs Python scripts on documents.
//
// Why bridges: Swift can call C++ directly, but not every C++ construct
// imports cleanly (heavy templates, exceptions, shared_ptr-based APIs).
// Keeping OpenUSD and MaterialX behind narrow APIs we control means the Swift
// side only ever sees simple types. See docs/spikes/M0a-materialx-from-swift.md
// and docs/spikes/M0b-storm-viewport.md.
//
// Why one package rather than one per kit: every package builds its own copy
// of everything it depends on, in its own .build folder. With OpenUSD in the
// dependencies, that was minutes per package. Here, all targets share one
// build. Add new modules as targets in this package.

// SWIFT: `import` makes another module's public declarations visible, like
// `#include` plus a namespace, but it imports a compiled module rather than
// pasting text. PackageDescription is the module that defines `Package`,
// `.target(...)` and so on.
import PackageDescription

// SWIFT: `let` declares a constant (it can never be reassigned). `var` would
// declare a variable. SwiftPM looks for a top-level constant named `package`.
let package = Package(
    // SWIFT: Arguments are labelled (`name:`), like Objective-C message
    // arguments. The labels are part of the function's name and are required.
    name: "MargolariaKit",

    // SwiftUsd requires macOS 14; we match the app's minimum (Config/Base.xcconfig).
    // SWIFT: `[...]` is an array literal. `.macOS(.v15)` is shorthand for
    // `SupportedPlatform.macOS(.v15)`: when Swift already knows the expected
    // type, you can leave out the type name and write just `.member`.
    platforms: [.macOS(.v15)],

    // Products are what other packages and the app can depend on.
    products: [
        .library(name: "MXKit", targets: ["MXKit"]),
        .library(name: "ViewportKit", targets: ["ViewportKit"]),
        .library(name: "PreviewKit", targets: ["PreviewKit"]),
        .library(name: "GraphKit", targets: ["GraphKit"]),
        .library(name: "ColorKit", targets: ["ColorKit"]),
        .library(name: "ScriptKit", targets: ["ScriptKit"]),
    ],

    // Packages this package depends on.
    dependencies: [
        // apple/SwiftUsd: OpenUSD v26.08 plus MaterialX 1.39.5, as prebuilt
        // dynamic frameworks. A local copy, patched to add the `OpenUSDCxx`
        // product (headers and frameworks only, without SwiftUsd's Swift
        // overlay, which we don't use and which dominated build times).
        // Create it with scripts/fetch-swiftusd.sh, which also pins the version.
        .package(name: "OpenUSD", path: "../../Vendor/SwiftUsd"),
    ],

    targets: [
        // C++ shim around MaterialX. SwiftPM compiles every .cpp file in
        // Sources/MXBridge, and its public headers live in Sources/MXBridge/include.
        .target(
            name: "MXBridge",
            dependencies: [
                // Links the OpenUSD and MaterialX frameworks, and puts their
                // headers on our include path.
                .product(name: "OpenUSDCxx", package: "OpenUSD"),
                // MaterialX's OSL generators (M5d), which SwiftUsd lacks.
                "MaterialXGenOsl",
            ],
            linkerSettings: [
                // ImageIO: which textures are greyscale (USDZ export, M5c).
                .linkedFramework("ImageIO"),
                .linkedFramework("CoreFoundation"),
            ]
        ),

        // The MaterialX Swift API.
        .target(
            name: "MXKit",
            dependencies: ["MXBridge"],
            swiftSettings: [
                // Lets this Swift module import C++ headers (MXBridge).
                // Any module that imports MXKit must turn this on too; the app
                // does it with SWIFT_OBJC_INTEROP_MODE in Config/Base.xcconfig.
                .interoperabilityMode(.Cxx),
            ]
        ),

        // Objective-C++ (.mm) wrapper around UsdImagingGLEngine and Storm.
        .target(
            name: "ViewportBridge",
            dependencies: [
                .product(name: "OpenUSDCxx", package: "OpenUSD"),
            ],
            linkerSettings: [
                .linkedFramework("Metal"),
            ]
        ),

        // The viewport: a SwiftUI view around an MTKView. ColorKit: OCIO's
        // view transform on Storm's frames (M3b). PreviewKit: the studio
        // light and DisplayPass, shared with the swatches (M3c).
        .target(
            name: "ViewportKit",
            dependencies: ["ViewportBridge", "ColorKit", "PreviewKit"],
            swiftSettings: [
                // ViewportBridge's own header is plain Objective-C, but its
                // module depends on OpenUSD's C++ modules, which Swift can
                // only load with C++ interop on.
                .interoperabilityMode(.Cxx),
            ]
        ),

        // Swatch rendering: compiles MaterialX's generated MSL and draws it
        // on a sphere. Pure Swift and Metal; no C++ of its own. ColorKit:
        // the view transform (M3c).
        .target(
            name: "PreviewKit",
            dependencies: ["MXKit", "ColorKit"],
            swiftSettings: [
                // Needed because it imports MXKit (see MXKit above).
                .interoperabilityMode(.Cxx),
            ]
        ),

        // OpenColorIO, built by scripts/build-ocio.sh (SwiftUsd doesn't
        // include it). A dynamic framework, embedded and signed in the app
        // like SwiftUsd's.
        //
        // SWIFT: A `binaryTarget` is a prebuilt library rather than source
        // code. SwiftPM links it, puts its headers on the include path of
        // the targets that depend on it, and Xcode embeds it in the app.
        .binaryTarget(
            name: "OpenColorIO",
            path: "../../Vendor/OpenColorIO/OpenColorIO.xcframework"
        ),

        // MaterialX's OSL shader generators, built from MaterialX 1.39.5's
        // sources against SwiftUsd's MaterialX by
        // scripts/build-materialx-genosl.sh, with MaterialX's library
        // compiled for the network form as resources (M5d). Embedded and
        // signed in the app like OpenColorIO.
        .binaryTarget(
            name: "MaterialXGenOsl",
            path: "../../Vendor/MaterialXGenOsl/MaterialXGenOsl.xcframework"
        ),

        // C++ shim around OpenColorIO, like MXBridge around MaterialX.
        .target(
            name: "ColorBridge",
            dependencies: ["OpenColorIO"]
        ),

        // Colour management in Swift (M3a).
        .target(
            name: "ColorKit",
            dependencies: ["ColorBridge"],
            swiftSettings: [
                // Lets this Swift module import C++ headers (ColorBridge).
                .interoperabilityMode(.Cxx),
            ]
        ),

        // The node graph canvas: model, layout, hit testing, and two
        // renderers (SwiftUI Canvas and Core Animation) compared in spike
        // M0d. Since M1 it builds its model from MXKit's graphs.
        .target(
            name: "GraphKit",
            dependencies: ["MXKit"],
            swiftSettings: [
                // Needed because it imports MXKit (see MXKit above).
                .interoperabilityMode(.Cxx),
            ]
        ),

        // Python 3.13, fetched by scripts/fetch-python.sh (M6): the
        // interpreter and its standard library, as one framework. Embedded
        // and signed in the app like OpenColorIO; its compiled modules are
        // signed by scripts/embed-python.sh.
        .binaryTarget(
            name: "Python",
            path: "../../Vendor/Python/Python.xcframework"
        ),

        // C++ shim around Python, like MXBridge around MaterialX (M6). It
        // includes MaterialX's headers too, only to hand MXBridge's
        // documents to PyMaterialX.
        .target(
            name: "PythonBridge",
            dependencies: [
                "MXBridge",
                "Python",
                .product(name: "OpenUSDCxx", package: "OpenUSD"),
            ],
            cxxSettings: [
                // The pybind11 headers PyMaterialX was built with
                // (scripts/build-pymaterialx.sh), which must be the same;
                // and Python's headers, which pybind11 includes as
                // <Python.h>, not as a framework's <Python/Python.h>.
                // `unsafeFlags` because the folders are outside the
                // package, which `headerSearchPath` doesn't allow. SwiftPM
                // refuses unsafe flags only in packages fetched from
                // elsewhere.
                //
                // SWIFT: `Context.packageDirectory` is this package's
                // folder, given to the manifest by SwiftPM, so the paths
                // don't depend on where the compiler runs.
                .unsafeFlags([
                    "-I", Context.packageDirectory + "/../../Vendor/PyMaterialX/include",
                    "-I", Context.packageDirectory
                        + "/../../Vendor/Python/Python.xcframework/macos-arm64/Python.framework/Headers",
                ]),
            ]
        ),

        // Running Python scripts on documents (M6).
        .target(
            name: "ScriptKit",
            dependencies: ["MXKit", "PythonBridge"],
            swiftSettings: [
                // Needed because it imports MXKit and PythonBridge.
                .interoperabilityMode(.Cxx),
            ]
        ),

        // Unit tests, run with `swift test` from this directory, or with
        // `xcodebuild test -scheme Margolaria` (shares the app's build).
        .testTarget(
            name: "MXKitTests",
            dependencies: ["MXKit"],
            // SWIFT: Files listed as resources are copied into the test bundle,
            // where tests find them with `Bundle.module`.
            resources: [.copy("Fixtures")],
            swiftSettings: [.interoperabilityMode(.Cxx)]
        ),

        // Model, layout, hit testing and marquee selection; building and
        // laying out MaterialX's example graphs.
        .testTarget(
            name: "GraphKitTests",
            dependencies: ["GraphKit", "MXKit"],
            resources: [.copy("Fixtures")],
            swiftSettings: [.interoperabilityMode(.Cxx)]
        ),

        // Conversions checked against the colour spaces' published formulas
        // and matrices. MXKit: every colour space MaterialX names must be
        // known to the config.
        .testTarget(
            name: "ColorKitTests",
            dependencies: ["ColorKit", "MXKit"],
            swiftSettings: [.interoperabilityMode(.Cxx)]
        ),

        // Renders swatches and saves them as PNGs; the view transform on
        // the GPU, checked against OCIO's CPU processor.
        .testTarget(
            name: "PreviewKitTests",
            dependencies: ["PreviewKit", "MXKit", "ColorKit"],
            resources: [.copy("Fixtures")],
            swiftSettings: [.interoperabilityMode(.Cxx)]
        ),

        // Scripts run on documents through PyMaterialX (M6).
        .testTarget(
            name: "ScriptKitTests",
            dependencies: ["ScriptKit", "MXKit"],
            swiftSettings: [.interoperabilityMode(.Cxx)]
        ),

        // Renders frames offscreen and saves them as PNGs, so a render can
        // be checked without running the app.
        .testTarget(
            name: "ViewportKitTests",
            // MXKit too: the M2c tests render the text MXKit writes for
            // previews. GraphKit: the M2e test builds a material through
            // the canvas's calls, then renders it.
            dependencies: ["ViewportKit", "MXKit", "GraphKit"],
            resources: [.copy("Fixtures")],
            swiftSettings: [.interoperabilityMode(.Cxx)]
        ),
    ],

    // OpenUSD and MaterialX are built as GNU C++17; our C++ must match.
    // (OpenColorIO is C++17 too, and ColorBridge.h exposes none of its types.)
    cxxLanguageStandard: .gnucxx17
)
