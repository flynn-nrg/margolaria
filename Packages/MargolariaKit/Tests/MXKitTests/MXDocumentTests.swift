// MXDocumentTests.swift
//
// Tests for MXKit: library loading, parsing, round-tripping, validation.
// Run them from Packages/MargolariaKit with `swift test`, or with
// `xcodebuild test -scheme Margolaria` from the repository root.
//
// Introduces (SWIFT): the Swift Testing framework (`@Test`, `#expect`,
// `#require`, `@Suite`), attributes and macros, `@testable import`,
// `do`/`catch`, `Bundle.module`.

import Foundation
// SWIFT: Swift Testing, the current test framework (it replaces XCTest).
import Testing

// SWIFT: `@testable` makes the module's `internal` declarations visible to the
// tests as well as its `public` ones. Only test targets may use it.
@testable import MXKit

/// Helpers shared by the tests below.
///
/// SWIFT: An enum with no cases can't be instantiated. It is the usual way
/// to make a pure namespace for static helpers, like a C++ namespace.
enum Fixtures {
    /// The URL of a file in Tests/MXKitTests/Fixtures.
    ///
    /// SWIFT: `Bundle.module` is generated by SwiftPM for targets that declare
    /// resources (see Package.swift). The `!` force-unwraps the optional URL:
    /// "this can't be nil; crash if it is". Avoid `!` in app code. In a test
    /// fixture lookup, a crash with a clear location is acceptable.
    static func url(_ name: String) -> URL {
        Bundle.module.url(forResource: name, withExtension: nil, subdirectory: "Fixtures")!
    }
}

// SWIFT: `@Suite` groups related tests and gives them a display name.
// `struct` is the conventional container: Swift Testing creates a fresh
// instance for each test, so tests can't leak state into each other.
@Suite("MXDocument")
struct MXDocumentTests {
    // SWIFT: `@Test` marks a function as a test. The string is the name shown
    // in reports. Test functions can be `throws`: an uncaught error fails the
    // test with the error's message, so there's no need for do/catch here.
    @Test("The bundled data libraries load")
    func bundledLibrariesLoad() throws {
        // SWIFT: `.get()` returns the success value, or re-throws the stored
        // error, which then fails the test with the error's message.
        let library = try MXLibrary.bundled.get()

        // SWIFT: `#expect` is a *macro* (the `#` marks it). It records a
        // failure if the condition is false, then the test continues. On
        // failure it prints the values on both sides of the comparison,
        // without extra code. Exact counts would make the test break on every
        // MaterialX update, so we check for "plausibly the full set".
        #expect(library.fileCount > 40)
        #expect(library.nodeDefinitionCount > 500)
    }

    @Test("Linked against MaterialX 1.39")
    func libraryVersion() {
        // SWIFT: `hasPrefix` is a String method; checks the start of the string.
        #expect(MXDocument.libraryVersion.hasPrefix("1.39"))
    }

    @Test("Reading a document lists its top-level elements in file order")
    func topLevelElements() throws {
        let document = try MXDocument.read(from: Fixtures.url("brushed_copper.mtlx"))

        // SWIFT: `.map(\.name)` takes the `name` of every element. `\.name` is
        // a *key path*: a reference to a property, usable as a function.
        let names = document.topLevelElements.map(\.name)
        #expect(names == ["NG_copper", "SR_copper", "M_BrushedCopper"])

        // SWIFT: `#require` is like `#expect`, but stops the test on failure.
        // Here it also unwraps the optional that `first(where:)` returns: if no
        // element matches, the test ends instead of crashing on a nil.
        let material = try #require(document.topLevelElements.first(where: { $0.name == "M_BrushedCopper" }))
        #expect(material.category == "surfacematerial")
        #expect(material.type == "material")
        #expect(material.childCount == 1)
    }

    @Test("Writing and re-reading a document preserves it")
    func roundTrip() throws {
        let original = try MXDocument.read(from: Fixtures.url("brushed_copper.mtlx"))
        let xml = try original.xmlString()
        let reread = try MXDocument(xml: xml)

        #expect(reread.topLevelElements == original.topLevelElements)
        // Writing the re-read document must produce exactly the same text:
        // after one pass through MaterialX, output is stable. That property is
        // what keeps saved files diffable in git (docs/PLAN.md §1.1).
        #expect(try reread.xmlString() == xml)
    }

    @Test("A valid document validates against the data libraries")
    func validDocument() throws {
        let document = try MXDocument.read(from: Fixtures.url("brushed_copper.mtlx"))
        document.setDataLibrary(try MXLibrary.bundled.get())
        #expect(document.validate() == .valid)
    }

    @Test("A node whose inputs match no nodedef fails validation")
    func invalidDocument() throws {
        // `base_color` must be a color3. As a float, no open_pbr_surface
        // nodedef matches this node, which MaterialX reports.
        //
        // SWIFT: A `"""` multi-line string literal. The closing `"""` sets the
        // indentation: that much leading whitespace is removed from each line.
        let xml = """
            <?xml version="1.0"?>
            <materialx version="1.39">
              <open_pbr_surface name="broken" type="surfaceshader">
                <input name="base_color" type="float" value="1.0" />
              </open_pbr_surface>
            </materialx>
            """
        let document = try MXDocument(xml: xml)
        document.setDataLibrary(try MXLibrary.bundled.get())

        // SWIFT: `if case` tests a value against one enum pattern and binds the
        // associated values. It's a one-case `switch`.
        if case .invalid(let messages) = document.validate() {
            #expect(!messages.isEmpty)
        } else {
            // SWIFT: `Issue.record` fails the test with a message.
            Issue.record("Expected validation to fail")
        }
    }

    @Test("Malformed XML throws parseFailed instead of crashing")
    func malformedXML() {
        // SWIFT: `#expect(throws:)` passes if the closure throws an error of
        // the given type. It is how you test error paths. This test exists
        // because of MXBridge's rule that C++ exceptions never reach Swift: if
        // the bridge let mx::ExceptionParseError escape, the process would
        // terminate instead of the test passing.
        #expect(throws: MXError.self) {
            try MXDocument(xml: "<materialx version=\"1.39\"><unclosed>")
        }
    }

    @Test("Documents from older versions are upgraded to 1.39 on load")
    func upgradesOldDocuments() throws {
        let xml = """
            <?xml version="1.0"?>
            <materialx version="1.38">
              <standard_surface name="SR_old" type="surfaceshader" />
            </materialx>
            """
        let document = try MXDocument(xml: xml)
        #expect(document.documentVersion == "1.39")
    }
}
